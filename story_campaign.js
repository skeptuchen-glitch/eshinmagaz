  function initCipher() {
    const syms = ['а', 'б', 'в', 'г', 'д'];
    const pool = [...syms];
    const secret = [];
    for (let i = 0; i < 3; i++) {
      const idx = Math.floor(Math.random() * pool.length);
      secret.push(pool.splice(idx, 1)[0]);
    }
    CIPHER = { secret, cur: [], hist: [] };
  }

